# The algorithms are:

# 1. Sorting Algorithms: These algorithms are used to arrange data in a
#    specific order, such as ascending or descending. Common sorting algorithms
#    include Bubble Sort, Insertion Sort, Selection Sort, Merge Sort, Quick
#    Sort, and Heap Sort. Each sorting algorithm has its own advantages and
#    disadvantages, and the choice of algorithm depends on factors such as the
#    size of the dataset, the nature of the data, and the desired time and
#    space complexity.

# 2. Searching Algorithms: These algorithms are used to find specific elements
#    within a dataset. Common searching algorithms include Linear Search,
#    Binary Search, and Hashing. Searching algorithms can be classified into
#    two main categories: linear search algorithms, which examine each element
#    in the dataset sequentially, and binary search algorithms, which divide
#    the dataset into smaller subarrays to locate the target element more
#    efficiently. The choice of searching algorithm depends on factors such as
#    the size of the dataset, the nature of the data, and the desired time and
#    space complexity.

# 3. Graph Algorithms: These algorithms are used to analyse and manipulate
#    graph data structures, which consist of nodes (vertices) and edges
#    connecting them. Common graph algorithms include Depth-First Search (DFS),
#    Breadth-First Search (BFS), Dijkstra's Algorithm, and the A* Algorithm.
#    Graph algorithms can be used to solve a wide range of problems,
#    such as finding the shortest path between nodes, detecting cycles in a
#    graph, and determining the connectivity of a graph. The choice of graph
#    algorithm depends on factors such as the size of the graph, the nature of
#    the data, and the desired time and space complexity.

# 4. Dynamic Programming Algorithms: These algorithms are used to solve
#    complex problems by breaking them down into simpler subproblems and
#    storing the results of these subproblems to avoid redundant calculations.
#    Common dynamic programming algorithms include the Fibonacci sequence, the
#    Longest Common Subsequence (LCS), and the Knapsack Problem. Dynamic
#    programming algorithms can be used to solve a wide range of optimisation
#    problems, such as finding the optimal solution to a problem with multiple
#    constraints. The choice of dynamic programming algorithm depends on
#    factors such as the size of the dataset, the nature of the data, and
#    the desired time and space complexity.

# 5. Greedy Algorithms: These algorithms are used to solve optimisation
#    problems by making a series of locally optimal choices in the hope of
#    finding a global optimum. Common greedy algorithms include Prim's
#    Algorithm, Kruskal's Algorithm, and the Huffman Coding Algorithm. Greedy
#    algorithms can be used to solve a wide range of problems, such as finding
#    the minimum spanning tree of a graph or constructing an optimal prefix
#    code. The choice of greedy algorithm depends on factors such as the size
#    of the dataset, the nature of the data, and the desired time and space
#    complexity. Think time tables.

# 6. Backtracking Algorithms: These algorithms are used to solve problems by
#    exploring all possible solutions and backtracking when a solution is found
#    to be invalid. Common backtracking algorithms include the N-Queens
#    Problem, the Sudoku Solver, and the Hamiltonian Path Problem. Backtracking
#    algorithms can be used to solve a wide range of combinatorial problems,
#    such as finding all possible arrangements of a set of elements or solving
#    constraint satisfaction problems. The choice of backtracking algorithm
#    depends on factors such as the size of the dataset, the nature of the
#    data, and the desired time and space complexity.

# 7. Divide and Conquer Algorithms: These algorithms are used to solve problems
#    by breaking them down into smaller subproblems, solving each subproblem
#    independently, and then combining the solutions to solve the original
#    problem. Common divide and conquer algorithms include Merge Sort, Quick
#    Sort, and the Fast Fourier Transform (FFT). Divide and conquer algorithms
#    can be used to solve a wide range of problems, such as sorting large
#    datasets or performing efficient polynomial multiplication. The choice of
#    divide and conquer algorithm depends on factors such as the size of the
#    dataset, the nature of the data, and the desired time and space
#    complexity.

# 8. Randomised Algorithms: These algorithms use randomisation to solve
#    problems more efficiently or to provide approximate solutions. Common
#    randomised algorithms include Randomised Quick Sort, Monte Carlo
#    Algorithms, and Las Vegas Algorithms. Randomised algorithms can be used
#    to solve a wide range of problems, such as finding approximate solutions
#    to optimisation problems or generating random samples from a dataset.
#    The choice of randomised algorithm depends on factors such as the size of
#    the dataset, the nature of the data, and the desired time and space
#    complexity.

