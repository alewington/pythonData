# dash Getting Started

# Dash is a Python framework for building analytical web applications.
# No JavaScript required.
# Built on top of Flask, Plotly.js, and React.js, Dash ties modern UI elements
# like dropdowns, sliders, and graphs directly to your analytical Python code.

# To install Dash, run the following command in your terminal:

# with pip:
# pip install dash

# With conda:
# conda install dash

# To check the version of Dash installed, run the following command in your
# terminal:

# python -c "import dash; print(dash.__version__)"

# To initiate dash, run the following command in your terminal:
# import dash

# To run the Dash app, execute the following command in your terminal:
# you will need the following packages installed: dash, pandas, plotly, flask.
